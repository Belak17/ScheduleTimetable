    public static Nationalite fromNationalite(String value) {
        if (value == null || value.isBlank()) {
            return null;
        }

        String normalized = value.trim();

        // 1. Recherche par code ISO (ex. : TD)
        for (Nationalite n : Nationalite.values()) {
            if (n.getCode().equalsIgnoreCase(normalized)) {
                return n;
            }
        }

        // 2. Recherche par nom du pays (ex. : Tchad)
        for (Nationalite n : Nationalite.values()) {
            if (n.getPays().equalsIgnoreCase(normalized)) {
                return n;
            }
        }

        // 3. Recherche par nom de nationalité (ex. : Tchadienne)
        for (Nationalite n : Nationalite.values()) {
            if (n.getNationalite().equalsIgnoreCase(normalized)) {
                return n;
            }
        }

        throw new IllegalArgumentException(
                "Nationalité invalide : " + normalized
        );
    }

